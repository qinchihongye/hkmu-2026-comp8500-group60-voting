export function toTraditionalChinese(input: string): string {
  if (!input) return input;
  let text = input;
  // 1. Convert specific phrases
  for (const [s, t] of PHRASE_MAP) {
    if (text.includes(s)) {
      text = text.replaceAll(s, t);
    }
  }
  // 2. Convert character by character
  let result = "";
  for (let i = 0; i < text.length; i++) {
    const ch = text[i]!;
    result += CHAR_MAP[ch] ?? ch;
  }
  return result;
}

